import json

contacts = []
for line in raw_data.strip().split('\n'):
    line = line.strip()
    if not line.startswith('*'):
        continue

    parts = line[1:].split(' : ')
    if len(parts) == 2:
        name = parts[0].strip()
        phones_str = parts[1].strip()

        has_phone = True
        phones = []
        if "(Namba haipo)" in phones_str:
            has_phone = False
        else:
            # Clean and parse phones
            raw_phones = [p.strip() for p in phones_str.split(',')]
            for rp in raw_phones:
                cleaned = rp.replace(' ', '')
                if cleaned:
                    phones.append(cleaned)

            if not phones:
                has_phone = False

        contacts.append({
            "name": name,
            "hasPhone": has_phone,
            "phones": phones
        })

ts_code = f"export type Contact = {{\n  name: string;\n  hasPhone: boolean;\n  phones: string[];\n}};\n\nexport const contactsData: Contact[] = {json.dumps(contacts, indent=2)};\n"

with open("src/lib/contacts.ts", "w") as f:
    f.write(ts_code)

